"""Regenerate site/demo-data.js from the test logs and the real komp output.

Run after changing the compressor:  cargo build --release && python3 scripts/build_site_demo.py
"""
import json, pathlib, re, subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
KOMP = ROOT / "target" / "release" / "komp"
PREVIEW_LINES = 40

DEMOS = [
    ("go", "Go · database outage", "go-logfmt-db-outage.log",
     "An orders service loses its Postgres connection, retries, then gives up."),
    ("java", "Spring Boot · NullPointerException", "java-spring-npe.log",
     "A checkout endpoint crashes 30 times with the same stack trace."),
    ("node", "Node.js · card declines", "node-json-payments.log",
     "JSON logs from a payments API: declines, slow fraud checks, healthy traffic."),
    ("k8s", "kubelet · CrashLoopBackOff", "kubelet-crashloop.log",
     "A pod that keeps crashing, seen from the Kubernetes node agent."),
]

demos = []
for key, label, file, about in DEMOS:
    path = ROOT / "tests" / "fixtures" / file
    raw = path.read_text()
    run = subprocess.run([str(KOMP), str(path)], capture_output=True, text=True, check=True)
    stats = re.search(r"(\d+) → (\d+) lines, ~(\d+) → ~(\d+) tokens", run.stderr)
    in_lines, out_lines, in_tok, out_tok = map(int, stats.groups())
    lines = raw.splitlines()
    demos.append({
        "key": key, "label": label, "about": about,
        "rawPreview": "\n".join(lines[:PREVIEW_LINES]),
        "rawLines": len(lines), "rawTokens": in_tok,
        "output": run.stdout.rstrip(), "outLines": out_lines, "outTokens": out_tok,
    })

out = ROOT / "site" / "demo-data.js"
out.write_text("// Generated by scripts/build_site_demo.py from tests/fixtures and real komp output.\n"
               "window.KOMP_DEMOS = " + json.dumps(demos, ensure_ascii=False, indent=1) + ";\n")
for d in demos:
    print(f'{d["key"]:5} {d["rawLines"]:5} lines ~{d["rawTokens"]:6} tok → {d["outLines"]:3} lines ~{d["outTokens"]:4} tok')
